export const TEXT: Record<Language, Text> = { sv, en };

export function languageOf(value: string | null | undefined): Language {
  return value === "en" ? "en" : "sv";
}

/** The phone's own language when the driver has not chosen. */
export function guessLanguage(): Language {
  const tags = typeof navigator === "undefined" ? [] : [...(navigator.languages ?? []), navigator.language];
  for (const tag of tags) {
    const code = String(tag ?? "").toLowerCase().slice(0, 2);
    if (code === "sv" || code === "nb" || code === "nn" || code === "no" || code === "da") return "sv";
    if (code) return "en";
  }
  return "sv";
}

